import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const UNICODE_VERSION = "17.0.0";
const UNICODE_DATA_URL = `https://www.unicode.org/Public/${UNICODE_VERSION}/ucd/UnicodeData.txt`;
const UNICODE_DATA_SHA256 = "2e1efc1dcb59c575eedf5ccae60f95229f706ee6d031835247d843c11d96470c";
const FIXTURE_PATH = fileURLToPath(
  new URL("../src/__tests__/fixtures/p2-pii-text-profile-v1.json", import.meta.url),
);
const GENERATED_PATH = fileURLToPath(
  new URL("../src/generated/piiTextProfile.ts", import.meta.url),
);

async function loadUnicodeData() {
  if (process.argv[2]) return readFile(process.argv[2]);
  const response = await fetch(UNICODE_DATA_URL);
  if (!response.ok) {
    throw new Error(`Failed to download ${UNICODE_DATA_URL}: HTTP ${response.status}`);
  }
  return Buffer.from(await response.arrayBuffer());
}

function parseFormatCharacterRanges(unicodeData) {
  const ranges = [];
  let pendingRange;

  for (const line of unicodeData.split("\n")) {
    if (!line) continue;
    const [codePointHex, name, category] = line.split(";");
    if (!(codePointHex && name && category)) {
      throw new Error(`Malformed UnicodeData.txt line: ${line}`);
    }

    const codePoint = Number.parseInt(codePointHex, 16);
    if (name.endsWith(", First>")) {
      if (pendingRange) throw new Error(`Nested UnicodeData.txt range at ${codePointHex}`);
      pendingRange = { start: codePoint, category };
      continue;
    }
    if (name.endsWith(", Last>")) {
      if (!pendingRange || pendingRange.category !== category) {
        throw new Error(`Unmatched UnicodeData.txt range at ${codePointHex}`);
      }
      if (category === "Cf") ranges.push([pendingRange.start, codePoint]);
      pendingRange = undefined;
      continue;
    }
    if (category === "Cf") ranges.push([codePoint, codePoint]);
  }

  if (pendingRange) throw new Error("Unterminated UnicodeData.txt range");

  const merged = [];
  for (const [start, end] of ranges) {
    const previous = merged.at(-1);
    if (previous && start <= previous[1] + 1) previous[1] = Math.max(previous[1], end);
    else merged.push([start, end]);
  }
  return merged;
}

function formatCodePoint(codePoint) {
  return codePoint.toString(16).toUpperCase().padStart(4, "0");
}

function updateFixture(source, ranges) {
  const expectedRanges = ranges.map(([start, end]) => [
    formatCodePoint(start),
    formatCodePoint(end),
  ]);
  const rangeLines = expectedRanges.map(([start, end]) => `    ["${start}", "${end}"]`).join(",\n");
  const updated = source
    .replace(/"unicodeVersion": "[^"]+"/, `"unicodeVersion": "${UNICODE_VERSION}"`)
    .replace(
      / {2}"formatCharacterRanges": \[[\s\S]*?\n {2}\]/,
      `  "formatCharacterRanges": [\n${rangeLines}\n  ]`,
    );
  const fixture = JSON.parse(updated);
  if (
    fixture.unicodeVersion !== UNICODE_VERSION ||
    JSON.stringify(fixture.formatCharacterRanges) !== JSON.stringify(expectedRanges)
  ) {
    throw new Error("Could not update the P2 text-profile fixture");
  }
  return updated;
}

function renderTypeScript(ranges) {
  const rangeLines = ranges
    .map(
      ([start, end]) =>
        `  [0x${formatCodePoint(start).toLowerCase()}, 0x${formatCodePoint(end).toLowerCase()}],`,
    )
    .join("\n");
  return `// Generated by scripts/generate-pii-text-profile.mjs. Do not edit.\n// Source: ${UNICODE_DATA_URL}\n// SHA-256: ${UNICODE_DATA_SHA256}\n\nexport const PII_TEXT_PROFILE_UNICODE_VERSION = "${UNICODE_VERSION}";\n\nexport const PII_FORMAT_CHARACTER_RANGES: ReadonlyArray<readonly [number, number]> = [\n${rangeLines}\n];\n`;
}

const unicodeData = await loadUnicodeData();
const actualHash = createHash("sha256").update(unicodeData).digest("hex");
if (actualHash !== UNICODE_DATA_SHA256) {
  throw new Error(
    `UnicodeData.txt SHA-256 mismatch: expected ${UNICODE_DATA_SHA256}, got ${actualHash}`,
  );
}

const ranges = parseFormatCharacterRanges(unicodeData.toString("utf8"));
const fixture = await readFile(FIXTURE_PATH, "utf8");
await writeFile(FIXTURE_PATH, updateFixture(fixture, ranges));
await writeFile(GENERATED_PATH, renderTypeScript(ranges));
console.log(`Generated ${ranges.length} Cf ranges for Unicode ${UNICODE_VERSION}`);
